import { expect, test, type ApiMock } from './fixtures/api.ts'

const host = {
  id: 'a',
  name: 'Local',
  connectionType: 'LOCAL',
  endpoint: 'unix:///var/run/docker.sock',
  status: 'UP',
  error: null,
  dockerVersion: '27.1.2',
  cpus: 8,
  memoryBytes: 16 * 1024 ** 3,
  containers: { running: 2, stopped: 0, healthy: 2, unhealthy: 0 },
  images: 1,
  volumes: 0,
}
const instance = {
  type: 'TRAEFIK',
  acmeEmail: 'ops@example.com',
  defaultCertMode: 'ACME_HTTP',
  dnsProvider: null,
  dnsCredentialsHint: null,
  deploymentId: 'd1',
  deploymentStatus: 'RUNNING',
}
const CONFIG = '/api/hosts/a/proxy/config'
const config = (custom: string) => ({
  type: 'TRAEFIK',
  managed: [{ name: 'managed.yml', content: 'http:\n  routers: {}\n' }],
  customFileName: 'custom.yml',
  custom,
  customUpdatedAt: null,
})

function setup(api: ApiMock, role: string) {
  api.mock('GET', '/api/auth/me', { body: { username: 'u', role, setupRequired: false } })
  api.mock('GET', '/api/hosts/overview', { body: [host] })
  api.mock('GET', '/api/hosts/a/proxy/managed', { body: { instance, setupBlockedReason: null } })
  api.mock('GET', '/api/hosts/a/proxy/certificates', { body: [] })
  api.mock('GET', '/api/hosts/a/proxy/routes', { body: [] })
  api.mock('GET', '/api/hosts/a/proxy/routes/status', { body: [] })
  api.mock('GET', '/api/hosts/a/proxy/routes/candidates', { body: [] })
  api.mock('GET', CONFIG, { body: config('') })
  api.mock('GET', `${CONFIG}/custom/versions`, { body: [] })
}

test('an admin edits the custom config, reviews the diff and saves only the custom content', async ({ page, api }) => {
  setup(api, 'ADMIN')
  await page.goto('/environments/a/domains')
  await expect(page.getByRole('heading', { name: 'Raw configuration' })).toHaveCount(0)
  await page.getByRole('switch', { name: 'Advanced mode' }).check()
  await expect(page.getByRole('heading', { name: 'Raw configuration' })).toBeVisible()

  // the generated tab explains that it is overwritten
  await page.getByRole('tab', { name: 'Generated by Shipir' }).click()
  await expect(page.getByText(/overwritten whenever/)).toBeVisible()
  await page.getByRole('tab', { name: 'Custom' }).click()

  // The editor is Monaco: type into it.
  await page.locator('.pce__editor .monaco-editor').first().click()
  await page.keyboard.type('http: {}')
  await expect(page.getByText('Unsaved changes')).toBeVisible()
  await page.getByRole('button', { name: 'Review changes' }).click()
  const dialog = page.getByRole('dialog', { name: 'Save your custom configuration?' })
  await expect(dialog.locator('.monaco-diff-editor')).toBeVisible()

  api.mock('PUT', `${CONFIG}/custom`, { body: config('http: {}') })
  const request = page.waitForRequest((r) => r.method() === 'PUT' && r.url().endsWith('/custom'))
  await dialog.getByRole('button', { name: 'Save' }).click()
  expect((await request).postDataJSON()).toEqual({ content: 'http: {}' })
  await expect(dialog).toHaveCount(0)
  await expect(page.getByText(/Saved\. The proxy uses/)).toBeVisible()
})

test('the validator message is shown inline and nothing is lost', async ({ page, api }) => {
  setup(api, 'ADMIN')
  await page.goto('/environments/a/domains')
  await page.getByRole('switch', { name: 'Advanced mode' }).check()
  await page.locator('.pce__editor .monaco-editor').first().click()
  await page.keyboard.type('foo: 1')
  await page.getByRole('button', { name: 'Review changes' }).click()
  api.mock('PUT', `${CONFIG}/custom`, { status: 400, body: { code: 'INVALID_PROXY_CONFIG', message: 'Top-level key "foo" is not allowed.' } })
  await page.getByRole('dialog').getByRole('button', { name: 'Save' }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Top-level key "foo" is not allowed.' })).toBeVisible()
  await expect(page.getByText('Unsaved changes')).toBeVisible()
})

test('an admin restores an earlier version after confirming', async ({ page, api }) => {
  setup(api, 'ADMIN')
  api.mock('GET', `${CONFIG}/custom/versions`, { body: [{ id: 'v1', createdAt: '2026-10-01T10:00:00Z', createdBy: 'alice', content: 'http: {}' }] })
  await page.goto('/environments/a/domains')
  await page.getByRole('switch', { name: 'Advanced mode' }).check()
  api.mock('POST', `${CONFIG}/custom/restore/v1`, { body: config('http: {}') })
  await page.getByRole('button', { name: /Restore the version from/ }).click()
  const request = page.waitForRequest((r) => r.method() === 'POST' && r.url().endsWith('/restore/v1'))
  await page.getByRole('dialog').getByRole('button', { name: 'Restore' }).click()
  await request
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

test('an operator never sees the raw configuration', async ({ page, api }) => {
  setup(api, 'OPERATOR')
  await page.goto('/environments/a/domains')
  await page.getByRole('switch', { name: 'Advanced mode' }).check()
  await expect(page.getByRole('heading', { name: 'Published domains' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Raw configuration' })).toHaveCount(0)
})
